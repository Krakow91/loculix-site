document.addEventListener("DOMContentLoaded", () => {
    const savedLang = localStorage.getItem('loculix_lang') || 'de';
    setLanguage(savedLang);

    const langToggle = document.getElementById('lang-toggle');
    if(langToggle) {
        langToggle.textContent = savedLang === 'de' ? 'EN' : 'DE';
        langToggle.addEventListener('click', () => {
            const currentLang = localStorage.getItem('loculix_lang') || 'de';
            const newLang = currentLang === 'de' ? 'en' : 'de';
            setLanguage(newLang);
            langToggle.textContent = newLang === 'de' ? 'EN' : 'DE';
        });
    }
});

function setLanguage(lang) {
    localStorage.setItem('loculix_lang', lang);
    const elements = document.querySelectorAll('[data-i18n]');
    
    elements.forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            // Check if it's an input placeholder
            if(el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                el.placeholder = translations[lang][key];
            } else {
                el.innerHTML = translations[lang][key];
            }
        }
    });

    // Refresh GSAP ScrollTriggers after DOM updates so animations don't break due to text height changes
    if (typeof ScrollTrigger !== "undefined") {
        setTimeout(() => {
            ScrollTrigger.refresh();
        }, 100);
    }
}
